#!/usr/bin/env python3
"""Generate dist/time-tracker: a single-file distribution runnable via uv."""

from __future__ import annotations

import argparse
import ast
import os
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
MODULE_DIR = REPO_ROOT / "src" / "time_tracker"
MODULES = ("durations", "storage", "tracker", "cli")
OUTPUT = REPO_ROOT / "dist" / "time-tracker"

HEADER = '''#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.11"
# dependencies = []
# ///
"""
time-tracker — single-file distribution.

Generated by tools/build_dist.py from src/time_tracker/; do not edit by hand.
"""

from __future__ import annotations
'''

ENTRY_POINT = """

if __name__ == "__main__":
    sys.exit(main())
"""


def _split_module(path: Path) -> tuple[str, list[ast.stmt], str]:
    """Split a module into (docstring, import nodes, remaining source).

    Import lines are removed from the source: the merged single file
    provides a unified import block, and relative/`__future__` imports are
    unnecessary once the modules are inlined.
    """
    source = path.read_text()
    tree = ast.parse(source)
    lines = source.splitlines(keepends=True)
    docstring = ""
    imports: list[ast.stmt] = []
    skipped: set[int] = set()

    first = tree.body[0] if tree.body else None
    if (
        isinstance(first, ast.Expr)
        and isinstance(first.value, ast.Constant)
        and isinstance(first.value.value, str)
    ):
        docstring = first.value.value
        skipped.update(range(first.lineno - 1, first.end_lineno))

    for node in tree.body:
        if not isinstance(node, (ast.Import, ast.ImportFrom)):
            continue
        skipped.update(range(node.lineno - 1, node.end_lineno))
        if isinstance(node, ast.ImportFrom) and (
            node.module == "__future__" or node.level > 0
        ):
            continue
        imports.append(node)

    body = "".join(line for index, line in enumerate(lines) if index not in skipped)
    return docstring, imports, body.strip("\n")


def _collect_imports(
    module_imports: list[list[ast.stmt]],
) -> tuple[list[str], dict[str, set[str]]]:
    """Merge import nodes into unique straight imports and from-imports."""
    straight: set[str] = set()
    froms: dict[str, set[str]] = {}
    for nodes in module_imports:
        for node in nodes:
            if isinstance(node, ast.Import):
                straight.update(
                    alias.name + (f" as {alias.asname}" if alias.asname else "")
                    for alias in node.names
                )
            else:
                assert node.module is not None
                target = froms.setdefault(node.module, set())
                target.update(
                    alias.name + (f" as {alias.asname}" if alias.asname else "")
                    for alias in node.names
                )
    return sorted(straight), froms


def _render_imports(module_imports: list[list[ast.stmt]]) -> str:
    straight, froms = _collect_imports(module_imports)
    blocks = ["\n".join(f"import {name}" for name in straight)]
    for module in sorted(froms):
        names = sorted(froms[module])
        line = f"from {module} import {', '.join(names)}"
        if len(line) <= 88:
            blocks.append(line)
        else:
            joined = ",\n    ".join(names)
            blocks.append(f"from {module} import (\n    {joined},\n)")
    return "\n".join(block for block in blocks if block)


def build() -> str:
    """Render the single-file distribution from the package sources."""
    module_imports: list[list[ast.stmt]] = []
    sections: list[str] = []

    for name in MODULES:
        docstring, imports, body = _split_module(MODULE_DIR / f"{name}.py")
        module_imports.append(imports)

        summary = docstring.splitlines()[0] if docstring else ""
        if len(summary) > 70:
            summary = summary[:67] + "..."
        banner = f"# {'-' * 72}\n# src/time_tracker/{name}.py"
        if summary:
            banner += f"\n# {summary}"
        banner += f"\n# {'-' * 72}"
        sections.append(f"{banner}\n\n{body}\n")

    imports_block = _render_imports(module_imports)
    return HEADER + "\n" + imports_block + "\n\n" + "\n\n".join(sections) + ENTRY_POINT


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the distribution is up to date without writing it",
    )
    args = parser.parse_args(argv)
    content = build()
    relative = OUTPUT.relative_to(REPO_ROOT)

    if args.check:
        current = OUTPUT.read_text() if OUTPUT.exists() else None
        if current == content:
            print(f"{relative} is up to date")
            return 0
        print(
            f"{relative} is out of date — regenerate with 'uv run tools/build_dist.py'",
            file=sys.stderr,
        )
        return 1

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(content)
    os.chmod(OUTPUT, 0o755)
    print(f"Wrote {relative} ({len(content.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
